// Helper to normalize search query (remove apostrophes, lowercase)
export function normalizeText(text: string): string {
  return text
    .toLowerCase()
    .replace(/[ʻʼ’'`]/g, "'")
    .trim();
}

// Find region by name or short name
export function findRegionByName(regionName: string): RegionData | undefined {
  const norm = normalizeText(regionName);
  return UZBEKISTAN_REGIONS.find(
    (r) =>
      normalizeText(r.name) === norm ||
      normalizeText(r.shortName) === norm ||
      normalizeText(r.name).includes(norm)
  );
}

// Filter regions based on user input (e.g. "sam" -> "Samarqand viloyati")
export function searchRegions(query: string): RegionData[] {
  const norm = normalizeText(query);
  if (!norm) return UZBEKISTAN_REGIONS;

  return UZBEKISTAN_REGIONS.filter(
    (r) =>
      normalizeText(r.name).includes(norm) ||
      normalizeText(r.shortName).includes(norm)
  );
}

// Filter districts for a given region (or across all if no region)
export function searchDistricts(regionName: string, query: string): string[] {
  const normQuery = normalizeText(query);
  const region = findRegionByName(regionName);

  const list = region
    ? region.districts
    : UZBEKISTAN_REGIONS.flatMap((r) => r.districts);

  if (!normQuery) return list;
  return list.filter((d) => normalizeText(d).includes(normQuery));
}
